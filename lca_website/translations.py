def get_translation(category, key, language="zh"):
    """Get translation for a specific key"""
    try:
        return TRANSLATIONS[category][key][language]
    except KeyError:

        return f"[{category}.{key}]"


def get_all_translations(language="zh"):
    """Get all translations for a specific language"""
    result = {}
    for category, items in TRANSLATIONS.items():
        result[category] = {}
        for key, translations in items.items():
            result[category][key] = translations.get(language, key)
    return result
